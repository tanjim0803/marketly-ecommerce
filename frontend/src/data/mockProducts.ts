export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProducts(categorySlug?: string): Product[] {
  const popular = products.filter((p) => p.isPopular);
  if (!categorySlug || categorySlug === "all") return popular;
  return popular.filter((p) => p.categorySlug === categorySlug);
}

export function getDealProducts(): Product[] {
  return products.filter((p) => p.isDeal && !p.isFeatured);
}

export function getFeaturedDeals(): Product[] {
  return products.filter((p) => p.isFeatured);
}
